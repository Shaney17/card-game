const ext = (
  expansionId: CatsExpansionId,
  id: string,
  name: string,
  description: string,
  count: number,
  opts: Partial<CatsCardDefinition> = {},
): CatsCardDefinition => ({
  id,
  name,
  description,
  imageKey: `cats.${id}`,
  category: 'action',
  expansionId,
  effectType: id,
  targetMode: 'none',
  requiresTarget: false,
  requiresChoice: false,
  count,
  nopeable: true,
  ...opts,
});

